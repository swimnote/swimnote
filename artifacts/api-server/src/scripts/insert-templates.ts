async function insertBatch(levelId: string, texts: string[]) {
  for (let i = 0; i < texts.length; i++) {
    const id = `dt_${Date.now()}_${Math.random().toString(36).slice(2, 8)}_${i}`;
    await superAdminDb.execute(sql`
      INSERT INTO diary_templates
        (id, swimming_pool_id, level_id, template_text, created_by, is_active, scope, sort_order, category)
      VALUES (
        ${id}, ${POOL_ID}, ${levelId}, ${texts[i]}, ${CREATED_BY},
        true, 'global', ${i}, 'general'
      )
    `);
  }
  console.log(`✅ ${texts.length}개 삽입 완료 (level: ${levelId})`);
}

